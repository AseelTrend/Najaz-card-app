// [FIX] عرض صحيح للمبالغ العشرية الصغيرة جداً.
//
// المشكلة: toStringAsFixed(2) العادي يقرّب أي قيمة أصغر من 0.005 إلى
// "0.00"، فتظهر أسعار مثل 0.0009 أو 0.00009 أو 0.000009 وكأنها صفر تماماً
// حتى عند زيادة الكمية. هذه الدالة تعرض القيم العادية بمنزلتين عشريتين
// كالمعتاد، وتزيد عدد الخانات تلقائياً فقط للقيم الصغيرة جداً بحيث تبقى
// القيمة الحقيقية ظاهرة دائماً مهما صغرت.
String formatMoney(double value) {
  if (value == 0) return '0.00';
  final abs = value.abs();
  // العتبة 0.005 لأنها بالضبط نقطة التقريب لـ toStringAsFixed(2):
  // أي قيمة أكبر أو تساوي 0.005 تُقرَّب أصلاً لرقم غير صفري ("0.01" فأكثر)
  // وتبقى كما كانت، والقيم الأصغر فقط (التي كانت تظهر "0.00" خطأً) هي
  // التي تحصل على خانات عشرية إضافية لإظهار قيمتها الحقيقية.
  if (abs >= 0.005) {
    return value.toStringAsFixed(2);
  }
  var s = value.toStringAsFixed(8);
  s = s.replaceFirst(RegExp(r'0+$'), '');
  if (s.endsWith('.')) s = '${s}0';
  return s;
}
